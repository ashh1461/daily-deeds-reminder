    fun getAyahs(surahNumber: Int): List<Ayah> {
        val specific = detailedAyahs[surahNumber]
        if (specific != null) {
            return specific
        }
        val surah = surahs.find { it.number == surahNumber } ?: return emptyList()
        return (1..surah.ayahCount).map { ayahNum ->
            Ayah(
                surahNumber = surahNumber,
                ayahNumber = ayahNum,
                textArabic = "آية رقم ($ayahNum) من سورة ${surah.nameArabic} المباركة",
                juz = surah.juzStart,
                page = surah.pageNumber
            )
        }
    }
